# Send the complete morning briefing by email
import os
import sys
import html
import smtplib
import subprocess

from datetime import datetime
from zoneinfo import ZoneInfo
from email.message import EmailMessage


# Programs that make up the morning briefing
BRIEF_SECTIONS = [
    ("WEATHER AND MARKET OVERVIEW", "main.py"),
    ("AI STOCK INVESTIGATION", "run_ai_brief.py"),
    ("PERSONALIZED NEWS", "news_brief.py")
]


def run_section(title, filename):
    """Run a briefing program and capture its results."""

    print(f"Generating: {title}", flush=True)

    # Run the Python file from the src folder
    result = subprocess.run(
        [sys.executable, filename],
        cwd=os.path.dirname(os.path.abspath(__file__)),
        capture_output=True,
        text=True,
        timeout=900,
        check=False
    )

    # Display warnings in GitHub logs
    if result.stderr:
        print(result.stderr[-2000:], file=sys.stderr)

    if result.returncode != 0:
        print(f"WARNING: {title} failed.")

        return (
            "This section is temporarily unavailable. "
            "Check GitHub Actions for details."
        )

    return result.stdout.strip() or "No results available."


def build_brief():
    """Collect all sections of the morning briefing."""

    sections = []

    for title, filename in BRIEF_SECTIONS:
        try:
            content = run_section(title, filename)

        except Exception as error:
            print(f"Section unavailable: {title}: {error}")

            content = "This section is temporarily unavailable."

        sections.append((title, content))

    return sections


def send_email(sections):
    """Send a formatted email using Gmail."""

    sender = os.environ["GMAIL_ADDRESS"]
    password = os.environ["GMAIL_APP_PASSWORD"]

    # Send to the same Gmail address for now
    recipient = sender

    # Use Rochester's local date
    today = datetime.now(
        ZoneInfo("America/New_York")
    ).strftime("%A, %B %d, %Y")

    subject = f"Your AI Morning Brief | {today}"

    # Build the plain-text version
    plain_text = f"AI MORNING BRIEF\n{today}\n\n"

    for title, content in sections:
        plain_text += (
            f"\n{'=' * 45}\n"
            f"{title}\n"
            f"{'=' * 45}\n"
            f"{content}\n"
        )

    # Build the HTML version
    html_sections = ""

    for title, content in sections:
        safe_title = html.escape(title)
        safe_content = html.escape(content)

        html_sections += f"""
        <div style="
            background: #ffffff;
            border: 1px solid #e5e7eb;
            border-radius: 12px;
            padding: 22px;
            margin-bottom: 20px;
        ">
            <h2 style="
                font-size: 17px;
                color: #1f2937;
                margin-top: 0;
            ">
                {safe_title}
            </h2>

            <div style="
                white-space: pre-wrap;
                overflow-wrap: anywhere;
                font-size: 14px;
                line-height: 1.7;
                color: #374151;
            ">{safe_content}</div>
        </div>
        """

    html_body = f"""
    <html>
    <body style="
        background: #f3f4f6;
        font-family: Arial, sans-serif;
        padding: 24px;
        margin: 0;
    ">
        <div style="max-width: 680px; margin: auto;">

            <div style="
                background: #1e293b;
                color: white;
                padding: 28px;
                border-radius: 12px;
                margin-bottom: 20px;
            ">
                <h1 style="margin: 0;">
                    Your AI Morning Brief
                </h1>

                <p style="margin-bottom: 0;">
                    {html.escape(today)}
                </p>
            </div>

            {html_sections}

            <p style="
                text-align: center;
                font-size: 12px;
                color: #6b7280;
            ">
                Generated by your AI Morning Brief Agent.
                AI summaries may contain errors.
                Financial analysis is informational only.
            </p>

        </div>
    </body>
    </html>
    """

    # Create the email
    message = EmailMessage()

    message["Subject"] = subject
    message["From"] = sender
    message["To"] = recipient

    message.set_content(plain_text)
    message.add_alternative(html_body, subtype="html")

    # Connect securely to Gmail and send
    with smtplib.SMTP_SSL(
        "smtp.gmail.com", 465, timeout=30
    ) as server:
        server.login(sender, password)
        server.send_message(message)

    print("Morning Brief email sent successfully!")


def main():
    print("Starting AI Morning Brief delivery...")

    # Generate all briefing sections
    sections = build_brief()

    # Send the completed email
    send_email(sections)


if __name__ == "__main__":
    main()
